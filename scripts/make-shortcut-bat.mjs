/**
 * 生成 `build/创建桌面快捷方式.bat`（免安装版 zip 里那个一键建图标的脚本）。
 *
 * ## 为什么用生成器而不是直接手写那个 .bat
 *
 * cmd.exe 在**打开 .bat 的那一刻**就按当前 OEM 码页决定了怎么解码整个文件；
 * 文件里写 `chcp` 只改**输出**编码，改不了正在读的句柄。所以：
 *
 *   · 中文写在 .bat 里 → 多字节序列会让后续行读取错位，`rem` 都兜不住，
 *     每一行都被当成非法命令（LF 行尾和 UTF-8 正文都实测崩过）
 *   · 想把中文正确显示出来，只能让 PowerShell 走 Unicode 控制台 API
 *
 * 于是这个脚本负责两件事：正文保持**纯 ASCII**，中文提示用
 * `powershell -EncodedCommand`（UTF-16LE 的 base64）带进去。
 * 直接手写 base64 不可维护，所以留这个生成器 —— **改文案改这里，不要改 .bat**。
 *
 * 用法：node scripts/make-shortcut-bat.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(root, 'build', '创建桌面快捷方式.bat');

/**
 * 中文提示 → 一段 PowerShell 脚本 → UTF-16LE base64（`-EncodedCommand` 要的形状）。
 *
 * 用 `[Console]::WriteLine` 而不是 `Write-Host`：后者走 PowerShell 的信息流，
 * 在 stdout 不是控制台时（有人把输出重定向到文件）会被序列化成一大坨
 * `<Objs ...>` CLIXML，糊满整屏。`[Console]::WriteLine` 直接写控制台流，
 * 重定向与双击两种情形行为一致。
 *
 * 代价是失去 `-ForegroundColor`。用 `[完成]` / `[错误]` / `[失败]` 前缀区分。
 */
function encoded(lines) {
  const script = lines.map((l) => `[Console]::WriteLine(${JSON.stringify(l)})`).join('; ');
  return Buffer.from(script, 'utf16le').toString('base64');
}

const MSG = {
  noExe: encoded([
    '',
    '  [错误] 同目录下找不到 OKPlay.exe。',
    '         请把这个文件放到 OKPlay.exe 旁边，再双击一次。',
    '',
  ]),
  ok: encoded([
    '',
    '  [完成] 已在桌面创建「OKPlay」快捷方式，双击即可开始学习。',
    '',
  ]),
  fail: encoded([
    '',
    '  [失败] 没能自动创建快捷方式。',
    '         可以手动来：右键 OKPlay.exe - 发送到 - 桌面快捷方式',
    '',
  ]),
};

/** 建快捷方式那行。**纯 ASCII** —— 就算所有提示都乱码，这条也照样生效。 */
const CREATE = [
  'powershell -NoProfile -ExecutionPolicy Bypass -Command',
  '"$w = New-Object -ComObject WScript.Shell;',
  "$s = $w.CreateShortcut('%LNK%');",
  "$s.TargetPath = '%TARGET%';",
  "$s.WorkingDirectory = '%APPDIR%';",
  "$s.IconLocation = '%TARGET%,0';",
  "$s.Description = 'OKPlay';",
  '$s.Save()"',
].join(' ');

/**
 * `-OutputFormat Text` 是必需的：PowerShell 在 stdout 不是控制台时（比如有人把
 * 输出重定向到文件）会切成 CLIXML 序列化，糊一大坨 `<Objs ...>` 出来。
 * 真实双击时 stdout 就是控制台、本来不会这样，但强制成文本让两种情形行为一致。
 */
const PS = 'powershell -NoProfile -ExecutionPolicy Bypass -OutputFormat Text -EncodedCommand';

const bat = `@echo off
setlocal EnableExtensions

rem ============================================================
rem  Portable (zip) helper -- creates an OKPlay desktop shortcut.
rem
rem  Why it exists: the zip is "unzip and run"; there is no
rem  installer, so nothing creates a shortcut for you. Double-click
rem  this file to add one.
rem
rem  It only points at the OKPlay.exe sitting next to it. No
rem  registry writes, no file copies. To undo: delete the desktop
rem  shortcut, then delete the folder you unzipped.
rem
rem  !! KEEP THIS FILE PURE ASCII WITH CRLF LINE ENDINGS !!
rem  cmd.exe picks the decoder for a .bat the moment it opens the
rem  file. A mid-file "chcp" changes OUTPUT encoding only, never
rem  the reader -- so Chinese text in here splits lines and gets
rem  executed as garbage commands. Both LF endings and UTF-8 body
rem  were tried; both broke the parser.
rem
rem  All Chinese output therefore goes through PowerShell
rem  -EncodedCommand (UTF-16LE base64), which writes via the
rem  Unicode console API and is immune to the code page.
rem
rem  DO NOT EDIT THIS FILE BY HAND. It is generated by
rem    node scripts/make-shortcut-bat.mjs
rem  Change the wording there.
rem
rem  The one plain "powershell -Command" line below is ASCII as
rem  well, so even if every message came out garbled the shortcut
rem  still gets created.
rem ============================================================

set "APPDIR=%~dp0"
set "TARGET=%APPDIR%OKPlay.exe"
set "LNK=%USERPROFILE%\\Desktop\\OKPlay.lnk"

if not exist "%TARGET%" (
  ${PS} ${MSG.noExe}
  pause
  exit /b 1
)

${CREATE}

if exist "%LNK%" (
  ${PS} ${MSG.ok}
) else (
  ${PS} ${MSG.fail}
)

pause
`;

const crlf = bat.replace(/\r\n/g, '\n').replace(/\n/g, '\r\n');
const bytes = Buffer.from(crlf, 'ascii');
const nonAscii = [...bytes.toString('latin1')].filter((c) => c.charCodeAt(0) > 127).length;

if (nonAscii > 0) {
  console.error(`生成失败：正文含 ${nonAscii} 个非 ASCII 字符 —— 必须保持纯 ASCII`);
  process.exit(1);
}

writeFileSync(OUT, bytes);
console.log(`[make-shortcut-bat] ${OUT}`);
console.log(`  纯 ASCII ✓  CRLF ✓  ${bytes.length} 字节`);
